#!/usr/bin/env node
/**
 * gate-exit — 门禁「自身故障」的唯一退出口（#843 P-2）。
 *
 * 为什么需要它：门禁的退出码此前没有单一事实源。同一件事（读不到输入 / 配置损坏 / 环境缺件）
 * 在仓内有三套写法（`process.exit(2)`、`exitCode = 2`、`return 2`）与各写一份的判词，
 * 于是「门禁自己坏了」与「判据判定不达标」在日志里不可区分。本轮真实事故正是把
 * `Build / Red-line approval` 的 exit 2 读成了「判据按设计判红」并汇报为「判决已生效」。
 *
 * 语义（唯一事实源见 AGENTS.md 的门禁一节，其余位置一律链向它，不再复述）：
 *   0 = 判据通过；
 *   1 = 判据按设计判红（结论可信：改动确实不达标）；
 *   2 = **门禁故障（非判据结论）**：门禁不可信，既不能读成「通过」也不能读成「不达标」。
 *
 * 只暴露 failClosed 一个入口：任何「这里还能继续往下跑」的中间态出口都会立刻长出第二份语义。
 */

/**
 * 以门禁故障（exit 2）结案：打印可检索的 `::error::` 注解后立即退出。
 *
 * 用 process.exit 而不是 process.exitCode：调用点全在「已经无法继续求值」的分支上，让控制流
 * 继续走等于拿未初始化的状态去判分——那正是本批次要消灭的失败方式。
 *
 * @param {string} why 故障原因；判词会被逐字拼接在固定前缀之后，故调用方不必自己带前缀
 */
export function failClosed(why) {
  console.error(`::error::门禁故障（非判据结论）：${why}`);
  process.exit(2);
}
