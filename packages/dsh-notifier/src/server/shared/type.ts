/**
 * dsh-notifier 包内 —— **跨域共享类型**。
 *
 * **准入判据**：被**三个以上**域使用、且**无单一域归属**的协议级 / 枚举级类型。
 *
 * 两个域共用一个类型不构成共享理由：那点耦合由「一方依赖另一方的契约」表达更
 * 诚实——进了公共层，两个域从此都不清楚这个类型该由谁负责演进，而它明明有主。
 * 判据卡在「第三个消费者出现」这一刻，是因为那正是「谁都不是主人」开始成立的
 * 时候。
 *
 * **不进本文件**：域的所有物——配置模型、投递消息、裁决结果、响应形状。它们留在
 * 各自域的 `type.ts`，由消费方的 `deps.ts` 声明依赖。
 *
 * 本文件零依赖：只被引用，不引用任何域。
 */

/**
 * 宿主日志出口的收窄面。
 *
 * 落在共享语言而非某个域的 `deps.ts`：config / stores / upgrade 三个域的装配入参
 * 都要它，而契约不得引用他域 `deps.ts`，放这里三方都能引。
 */
export interface LoggerPort {
  warn(message: string): void;
}
