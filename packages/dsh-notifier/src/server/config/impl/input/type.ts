import type { SettingInvalid } from "../model/type.ts";

/**
 * 校验结果。
 *
 * 用具名判别联合而不是空值哨兵：调用方不必猜「空」是「通过了」还是「没东西可
 * 校验」，而失败载荷是结构化的，界面能直接定位到字段。
 */
export type ValidationResult = { ok: true } | { ok: false; error: SettingInvalid };
/**
 * 一次写里「本次改动 vs 存量带回」的判定器（issue #1016 批次 B 使能面）。
 *
 * 做成**带方法的查询面**而不是 `Map<id, Set<field>>`：那条路线要求每个消费方自己写一遍
 * 「base 里没有这个 id ⇒ 全部字段算改动」的兜底，而漏写兜底的后果正是本机制要防的那件事
 * ——把用户没碰过的存量非法值当成本次改动拒掉，把人锁死在设置页外面。兜底收在这一处，
 * 消费方只问「这个字段算不算本次改动」。
 *
 * 口径：**逐字比对**。掩码还原后的字段与 base 同 id 频道的同名字段逐字节相同 ⇒ 原样带回；
 * base 里没有该 id（新增频道）⇒ 全部字段都是本次改动。
 *
 * **两条系统性盲区**（本机制的固有代价，不是实现漏写；下游的边界值判据必须自己知道，否则会
 * 以为「机制给的读数就是真相」）：
 *
 * (a) **同一批键上有一对读数相反的手势，方向会翻转**。基线是「客户端看过的那份视图」，它按类型
 * 补齐了服务端默认值，而提交侧只剥空串、**不补默认值**——两侧这一条不对称就是 (a) 的全部来源。
 * 它分成方向相反的两半：**「设成默认值」读不出，「清空默认值」却读得出**：
 *
 *   半边 1｜【主动设成服务端默认值】⇒ 读不出（漏拒）
 *     磁盘 999999，用户只改名字        ⇒ false（正确）
 *     磁盘 999999，用户【主动】设成 0  ⇒ false（真改动读不出）
 *     磁盘无该键，用户【主动】设成 0   ⇒ false（同上）
 *     磁盘 600000，用户设成 5000       ⇒ true（真实越界，读得出）
 *     不止 timeoutMs：bark 的 levels 空对象、webhook 的 auth:'none' / preset:'custom' /
 *     headers:{} / timeoutSec:0 同理。方向可接受（漏拒比错杀轻）。
 *
 *   半边 2｜【清空一个「已经是服务端默认值」的字段】⇒ 读作「本次改动」（幻影字段）
 *     磁盘无 timeoutSec（生效值 0），用户只改名字      ⇒ false（正确）
 *     同上，用户改名 + 把超时框清空（删键）            ⇒ **true**（幻影：用户没碰过这个字段的值）
 *     同上，用户改名 + 显式填成 0（与生效值相同）      ⇒ false（读不出）
 *
 *   **半边 2 的方向与半边 1 相反，且与本文其余各条都不同**：清空读 true、填默认值读 false，
 *   而这两下手势在用户看来是同一件事（「我要的就是 0」）。根因是基线侧过「剥空串 + 补默认值」、
 *   提交侧只过「剥空串」——于是「客户端删掉了一个基线侧**仅靠补默认值才存在**的键」必然读成不同
 *   （键在基线里有、提交里没有）。受影响的键是**七个补默认值的字段**：bark `enabled`/`timeoutMs`/
 *   `levels`、webhook `auth`/`preset`/`headers`/`timeoutSec`；其中**界面能真删掉的只有两个**——
 *   `timeoutSec`（数字框退格）与 `levels`（清空级别），都是一两次点击可达。
 *
 *   **当前无实际误拒**：缺席的 `timeoutSec`/`levels` 不违反任何现有判据（实测：三条手势的校验
 *   结论逐字相同，都是 ok），本机制是使能面、不据以拒任何东西。但**契约文本必须写全**：照
 *   「方向都是读不出」去写的下游判据，在 `true` 这一侧完全没有准备，会把幻影字段当成「用户刚改
 *   的」去过拒边界值。对称化修复（让两个手势读数一致）**另立 issue，不在本 PR**。
 *   要判「用户是否主动设成了默认值」，得回去比对磁盘原值，不能只看本面。
 *
 * (b) **重复 id 的「少一条」读不出**。基线按 id 建索引、提交侧按出现次序取，两条同 id 的
 *   提交项在「只剩一条」时与「两条都在」读数完全一样（实测：基线两条 b1、提交只剩一条且
 *   内容与首条相同 ⇒ isEdited / isNewChannel / isEditedAt 全 false 或无信号）。
 *   注意这**只**发生在重复 id 上：删掉一整条**不同 id** 的频道读得出（按 id 问是「提交里
 *   没有这个 id ⇒ 删了它」）。要拒「用户删掉了重复项里的一条」，得自己数数组长度。
 *
 *   重复 id 的代价**不止「读不出」这一半**，另一半在**写面**且方向相反：掩码还原按 id 取**首条**
 *   的原值，于是磁盘上两条同 id、凭据不同的 webhook（token AAA / BBB）保存一次之后，**第二条的
 *   token 被静默改成 AAA**——凭据被覆盖、不可逆，用户没有任何提示。实测读数：两条的
 *   `isEdited("dup:1","token")` 都是 false（读不出「第二条被改了」），而 `isEditedAt` 对第二条
 *   是 true（读成「用户刚改过它」——真凶是覆盖，不是人）。本机制**没有制造也没有掩盖**这条：
 *   掩码还原住在 redact 域（`src/server/config/impl/redact/index.ts`），本 PR 对它 diff 0 行；
 *   但机制是使能面，下游凭据判据要按「重复 id ⇒ 写面按首条还原」来做预期，**登记待下游**，
 *   另立 issue 修，不在本 PR。
 */
export type ChannelWriteScope = {
  /**
   * 该频道的该字段是否属于**本次改动**。
   *
   * **id 重复时首条胜出**（基线按 id 建索引取第一条）：同 id 的多条提交项拿到同一份基线，
   * 第二、三条改了什么都读不出来。要逐元素地问那一条（「这两条重复的是不是同一条」），走
   * `isEditedAt`——按下标定位**提交**里的那一条，按它的出现次序取基线。实测：基线两条 b1
   * （timeoutMs 1、2）、提交三条 b1（1、2、3），本方法读 `isEdited("b1","timeoutMs")` 仍是
   * false，而 `isEditedAt(2, …)` 是 true。
   *
   * @param channelId 频道 id（按 id 对齐，不按下标：数组顺序一变就会张冠李戴）。
   * @param field 频道条目内的字段名。
   * @returns base 里没有该 id、或该字段与 base 逐字不同时为 true。
   *   读不出「用户主动设成服务端默认值」与「重复 id 少一条」这两种改动，见类型头的两条盲区。
   */
  isEdited(channelId: string, field: string): boolean;
  /**
   * 该频道是否是**本次新增**（base 里没有同 id 的条目）。
   *
   * 单列一条而不是让消费方从 `isEdited` 反推：新增频道的「全部字段都是改动」是兜底结论，
   * 不是逐字段比对的结果，两者在话术与后续判据上要能分开用。
   */
  isNewChannel(channelId: string): boolean;
  /**
   * 按**提交数组下标**问同一件事：提交里第 `index` 项的该字段是否属于本次改动。
   *
   * 为什么需要它：`isEdited(channelId, …)` 按 id 对齐且**首条胜出**，id 重复时两条提交项拿到
   * 的是同一份基线——第二条改了什么都读不出来。重复 id 判据要回答的恰恰是第二条（它得逐元素地
   * 说清「重复的是不是同一条」），只有下标能定位到具体那一条；别的消费方不该自己去解构 patch
   * 数组取元素，故在此开一个只读入口。
   *
   * 对齐口径：**同 id 的第 k 条对第 k 条**（提交里第 k 条该 id 的条目，比基线里第 k 条该 id 的
   * 条目）。刻意不按下标对齐（数组整体换序就张冠李戴），也不复用 `isEdited`（那边首条胜出，
   * 会把第二条的改法吞掉）。id 唯一时两者等价。
   *
   * 兜底方向与本类型其余各条同向「本次改动」：下标越界、该项不是带非空 id 的频道对象、
   * 存量里没有同 id 的第 k 条（本次多出来的一条）。
   *
   * @param index 提交频道数组里的下标（不是基线里的下标——基线的下标对调用方没有意义）。
   * @param field 该项内的字段名。
   */
  isEditedAt(index: number, field: string): boolean;
};

/**
 * 带存量基线的校验结论。
 *
 * 带基线只是为了把「本次改动」这份信息交给校验层；**判定结论与不带基线时逐字相同**
 * （本机制不加任何新判据），两者并排放在返回值里正是为了让这个不变式可断言。
 */
export type ScopedValidationResult = {
  verdict: ValidationResult;
  scope: ChannelWriteScope;
};
