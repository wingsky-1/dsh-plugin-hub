/**
 * dsh-notifier upgrade 域 —— 升级链自己的形状。
 */
/**
 * 一步升级：把存储从 `fromVersion` 的形态推进到 `targetVersion`。
 *
 * 两端都写出来而不是只写目标：只写目标的话，「这一步管的是哪一段」要靠与前后步骤
 * 比对才能推出来，而链的中间步骤恰恰是最需要一眼看清边界的——一个版本的迁移函数
 * 有没有覆盖它该覆盖的形态，看的就是这两个端点。
 *
 * 步骤是**刻度**而不是迁移函数的别名：没有数据要改的版本也给一步（`run` 空实现），
 * 因为链的推进以步骤为刻度——漏掉一个版本，存储刻度就会永久停在那里，而「版本
 * 没变」与「升级没做完」在外部表现上一模一样。
 */
export interface UpgradeStep {
  /** 起点版本：这一步处理的存储形态对应的版本（升级**前**的那个版本）。 */
  fromVersion: string;
  /**
   * 目标版本：这一步完成后**回写**进 `version` 文件的刻度。
   *
   * 刻度由链驱动统一回写，不由步骤自己写：步骤只管改数据，写完数据再写刻度，
   * 这个顺序一旦交给各步骤自行安排，就会出现「数据改了一半、刻度已经前进」的
   * 存储——而那种存储没有任何办法退回。
   */
  targetVersion: string;
  /** 迁移动作；失败即抛，启动随之中止。 */
  run(): void;
}
