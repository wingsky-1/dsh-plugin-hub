/**
 * dsh-notifier upgrade 域 —— **对外契约**。
 *
 * ## 职责边界
 *
 * **存储形态的版本迁移**：把磁盘上的数据从它被写下时的形态，逐版本推到当前代码
 * 认识的形态。它不认识通知业务，也不认识各域——只认「文件从哪来、到哪去、内容
 * 怎么改写」，因此没有任何域依赖。
 *
 * ## 为什么要有独立刻度
 *
 * 数据形态与代码形态的变更节奏不同步：一次重构可能连着改布局、改键名、改默认值，
 * 而下一个版本可能什么都不用改。只靠「插件版本」判断「数据是不是旧的」区分不开
 * 「升级没做完」与「本来就没得升」，所以存储自己记一个刻度（`version` 文件），
 * 由本域独占读写。
 *
 * ## 为什么必须在装配之前
 *
 * 升级会重写配置文件与存储文件。先装配各域，就等于让它们先读到旧形态、带着旧形态
 * 继续跑——之后再改文件也改不动已经在内存里的那份。
 *
 * ## 依赖方向
 *
 * 只引本域 `./impl/`（契约调实现）与本域装配入参申报表 `./deps.ts`（类型面）；
 * 不引任何他域实现。
 */
import type { LoggerPort } from "../shared/type.ts";
import { runUpgradeChain } from "./impl/chain/index.ts";

/** 装配入参。 */
export interface UpgradeDeps {
  /** 升级链的诊断出口（失败与版本落差都在这里出声）。 */
  logger: LoggerPort;
}

/**
 * 跑一遍升级链（组合根在各域装配之前调用一次）。
 *
 * 同步且幂等：没有待做的步骤时只读一次版本文件。**任何一步失败即抛出**，`apply`
 * 随之失败、插件不启动——带半完成迁移的存储比不启动危险得多，后者可见，前者只会
 * 安静地把数据读错。
 *
 * 抛出的那一步不回写刻度，下次启动从同一步重跑，所以迁移函数必须自己保证重跑安全
 * （幂等）——这是本域对步骤实现的唯一硬要求。
 */
export function installUpgrade(deps: UpgradeDeps): void {
  runUpgradeChain(deps.logger);
}
