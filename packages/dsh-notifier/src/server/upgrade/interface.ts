/**
 * dsh-notifier upgrade 域 —— **对外契约**。
 *
 * ## 职责边界
 *
 * **存储形态的版本迁移**：把磁盘上的数据从它被写下时的形态，逐版本推到当前代码认识
 * 的形态。它不认识通知业务——只认「旧数据从哪来、到哪去、内容怎么改写」。
 *
 * 它要的唯一跨域能力是 config 域的**写面**：存量设置的落点是当前配置文件。旧版本长什么
 * 样的知识全部留在本域（`impl/legacy/`），业务域因此永远不必为历史包袱背依赖。
 *
 * ## 为什么要有独立刻度
 *
 * 数据形态与代码形态的变更节奏不同步：一次重构可能连着改布局、改键名、改默认值，
 * 而下一个版本可能什么都不用改。只靠「插件版本」判断「数据是不是旧的」区分不开
 * 「升级没做完」与「本来就没得升」，所以存储自己记一个刻度（`version` 文件），
 * 由本域独占读写。
 *
 * ## 为什么必须在装配之前
 *
 * 升级会重写配置文件与存储文件。先装配各域，就等于让它们先读到旧形态、带着旧形态
 * 继续跑——之后再改文件也改不动已经在内存里的那份。
 *
 * 唯一的例外是存量配置（见 `installUpgrade`）：它要先等宿主 settings 服务就绪，因此挂
 * 在回调上而不是链里。
 *
 * ## 依赖方向
 *
 * 只引本域 `./impl/`（契约调实现）与本域依赖声明 `./deps.ts`；不引任何他域实现。
 */
import type { UpgradeDeps } from "./deps.ts";
import { upgradeRunner } from "./impl/service/index.ts";

/**
 * 装配升级域（组合根在各域装配之前调用一次）。
 *
 * 两件事、两种时机：升级链**同步跑完**（幂等：没有待做的步骤时只读一次版本文件，任何
 * 一步失败即抛出、`apply` 随之失败——带半完成迁移的存储比不启动危险得多）；存量配置的
 * 迁移挂在宿主 settings 服务就绪的回调上，等不到就不做。
 *
 * 抛出的那一步不回写刻度，下次启动从同一步重跑，所以迁移函数必须自己保证重跑安全
 * （幂等）——这是本域对步骤实现的唯一硬要求。
 */
export function installUpgrade(deps: UpgradeDeps): void {
  upgradeRunner.install(deps);
}

/**
 * 卸载升级域（组合根在卸载期调用）。
 *
 * 只退订那一次等待：升级链本身没有留下需要释放的东西——它写的是文件。
 */
export function releaseUpgrade(): void {
  upgradeRunner.release();
}
