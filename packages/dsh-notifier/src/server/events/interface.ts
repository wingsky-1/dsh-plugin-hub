/**
 * dsh-notifier events 域 —— **对外契约**。
 *
 * ## 职责边界
 *
 * **宿主事件 → 通知请求**：订阅宿主的事件流，认出哪一件对应哪一种通知，把结果交给
 * 出口。本域不投递、不落盘、不脱敏、不认识浏览器，**也不判断该不该发**——事件开关、
 * 免打扰时段、频道选择都属于裁决层。
 *
 * 最后这条边界是刻意的。如果本域也看开关，那「开关关了就静默」这条规则就同时存在
 * 于两处，而只要有一处漏读，用户看到的就是「设置改了不起作用」。开关总在变化，本域
 * 却只在事件到达那一刻才可能去看它——把运行期策略放进一个按事件驱动的块里，本身就
 * 是在赌「每次都会记得看」。
 *
 * 所以本域产出的是**陈述**（刚刚发生了什么），不是**决定**（要不要打扰）。开关关着
 * 时请求照样产出，由裁决层丢弃：这比在本域提前拦截更便宜，也更不容易错。
 *
 * ## 为什么出口是入参
 *
 * 「通知请求去哪」不属于本域：它可以是裁决管线、可以是测试替身、将来也可以是别的
 * 消费者。做成入参，这个问题就只有一个地方需要回答；做成对本域下游的硬引用，换一
 * 个消费者就要动本域一次。
 *
 * ## 为什么只旁观审批
 *
 * 宿主的 `approval/request` 是 **waterfall**：监听者要么自己裁决、要么调用 `next()`
 * 把判定交还。本域只想知道「有人要审批」，不参与裁决——组合根负责在转发之后调用
 * `next()`。缺了那一步，本域就会把别人的审批请求吞掉，而症状是「审批不弹了」，
 * 与本域毫无字面关联。
 *
 * ## 为什么是「装配 + 具名释放」而不是交出句柄
 *
 * 订阅是**有状态**的：装了几条就要摘几条。状态收在实现里，对外只给一对动作——
 * 外面拿不到句柄就造不出第二份订阅，「只订阅一次」才有物理含义。
 *
 * 释放做成具名动作而不是 `install` 的返回值：返回一个闭包，等于把「谁负责摘干净」
 * 交给调用方保管，而这本来就是这个域的责任。具名之后装与卸在契约上对称，卸载链要
 * 的也只是一个函数引用，不必替调用方保存闭包。
 *
 * ## 依赖方向
 *
 * **依赖方向**：只引本域 `./impl/`（契约调实现）；本域无对上依赖，故不建 `deps.ts`——
 * 通知请求的每个字段都是本域自己的词汇（kind 是内置种类，标题正文是原样文本），
 * 没有一样需要向他域借形状。
 */
import { eventListener } from "./impl/listen/index.ts";
import type { EventsDeps } from "./impl/listen/type.ts";

// 入参类型：只出「调用方必须构造的」——组合根要造宿主事件面与出口。
export type { EventsDeps, HostEventPort } from "./impl/listen/type.ts";
export type { NotifyKind, NotifyRequest } from "./impl/translate/type.ts";

/**
 * 装配事件订阅（组合根在 `apply` 期调用一次）。
 */
export function installEvents(deps: EventsDeps): void {
  eventListener.install(deps);
}

/**
 * 摘除全部订阅（组合根在卸载期调用）。
 *
 * 与 `installEvents` 配对；重复调用无害。
 */
export function releaseEvents(): void {
  eventListener.release();
}
