/**
 * dsh-notifier events 域 —— 翻译块自己的形状。
 *
 * 翻译是**单向**的：宿主事件进、通知请求出。本块不知道请求会被谁消费、怎么投递，
 * 也不回看宿主——它只回答「刚刚发生了什么」。
 */

/**
 * 内置通知种类：本域产出、裁决层消费的那套词汇表。
 *
 * 它是**裁决的坐标系**——事件开关、`kindRoutes`、`allowKinds`、bark 的按 kind 紧急度
 * 全按它查。收成字面量联合而不是宽 `string`，是为了让裁决层的映射表拿到穷举检查：
 * 漏写一个 kind 是编译错误，而不是「某种通知静默地不发了」——后者没人会去查。
 *
 * 动态 kind（外部注册的通知种类）不在这个联合里：那是一套独立的白名单机制，等 sdk
 * 域落地时单独开口，不在这里放宽成 `string` 把内置 kind 的检查一起赔掉。
 */
export type NotifyKind =
  | "ask"
  | "question"
  | "task-done"
  | "subagent-done"
  | "task-error"
  | "turn-end";

/**
 * 通知请求：一次「发生了什么」的陈述。
 *
 * 刻意**不叫「要通知」**：本域已经不再判断该不该发。开关、免打扰、路由、频道选择
 * 全是裁决层的事——它们都随设置变化，而设置在本域看不见的地方被改。让本域每次都
 * 去问一遍「现在开着吗」，等于把一条运行期策略摊进翻译逻辑里，而它本来只需要认事件。
 *
 * 与投递域的消息（`NotifyMessage`）也不是同一个东西，也不该合并：请求是**未加工的
 * 陈述**，消息是**已定稿的载荷**。合起来就会让加工那几道工序落到翻译块里，而它们
 * 属于下游。
 */
export interface NotifyRequest {
  /** 事件种类：裁决层据此查事件开关与频道路由。 */
  kind: NotifyKind;
  /** 标题与正文（原样，未经下游加工）。 */
  title: string;
  body: string;
}

/**
 * 翻译结果。
 *
 * 用具名判别联合而不是空返回值：**大多数宿主事件都不对应任何一种通知**（流式增量、
 * 请求上下文、步骤起止……），这不是异常路径而是常态。把常态表达成「没有值」，
 * 调用方就得到处判空。
 *
 * 注意它与「开关关着」是两回事：这里说的是「这件事不构成通知」，而「这件事构成
 * 通知但现在不该发」是裁决层的判断。
 */
export type Translation = { ok: true; request: NotifyRequest } | { ok: false };
