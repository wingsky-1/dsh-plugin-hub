/**
 * dsh-notifier events 域 —— 翻译块自己的形状。
 *
 * 翻译是**单向**的：宿主事件进、通知请求出。本块不知道请求会被谁消费、怎么投递，
 * 也不回看宿主——它只回答「刚刚发生了什么」。
 */
import type { NotifySeverity } from "../../deps.ts";

/**
 * 通知请求：一次「发生了什么」的陈述。
 *
 * 刻意**不叫「要通知」**：本域已经不再判断该不该发。开关、免打扰、路由、频道选择
 * 全是裁决层的事——它们都随设置变化，而设置在本域看不见的地方被改。让本域每次都
 * 去问一遍「现在开着吗」，等于把一条运行期策略摊进翻译逻辑里，而它本来只需要认事件。
 *
 * 与投递域的消息（`NotifyMessage`）也不是同一个东西，也不该合并：请求是**未加工的
 * 陈述**（正文还没脱敏、还没渲染、还没决定发给谁），消息是**已定稿的载荷**。
 * 合起来就会让「脱敏」与「渲染」这两道工序落到翻译块里，而它们属于下游。
 */
export interface NotifyRequest {
  /** 事件种类：裁决层据此查事件开关与频道路由。 */
  kind: string;
  /** 展示强度（仅展示；过滤语义归 kind）。 */
  severity: NotifySeverity;
  /** 标题与正文（未脱敏、未渲染）。 */
  title: string;
  body: string;
}

/**
 * 翻译结果。
 *
 * 用具名判别联合而不是空返回值：**大多数宿主事件都不对应任何一种通知**（流式增量、
 * 请求上下文、步骤起止……），这不是异常路径而是常态。把常态表达成「没有值」，
 * 调用方就得到处判空。
 *
 * 注意它与「开关关着」是两回事：这里说的是「这件事不构成通知」，而「这件事构成
 * 通知但现在不该发」是裁决层的判断。
 */
export type Translation = { ok: true; request: NotifyRequest } | { ok: false };
